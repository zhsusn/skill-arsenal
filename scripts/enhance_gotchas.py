def main():
    for rel_path, new_gotchas in ENHANCEMENTS.items():
        skill_md = ROOT / rel_path / "SKILL.md"
        if not skill_md.exists():
            print(f"SKIP (not found): {skill_md}")
            continue

        text = skill_md.read_text(encoding="utf-8")
        # Replace everything from "## Gotchas" to end of file
        pattern = r"## Gotchas\n.*"
        if not re.search(pattern, text, re.DOTALL):
            print(f"SKIP (no Gotchas): {skill_md}")
            continue

        text = re.sub(pattern, lambda m: new_gotchas, text, flags=re.DOTALL)
        skill_md.write_text(text, encoding="utf-8")
        print(f"OK: {rel_path}")


if __name__ == "__main__":
    main()
